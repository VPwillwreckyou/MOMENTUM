import type { Category, Goal } from '../state/types';
import { computeGoalProgress } from './progress';
import { formatDate, parseDateOnly } from './dates';
import { recurrenceLabel } from './recurrence';

function hexToRgb(hex: string): [number, number, number] {
  const clean = hex.replace('#', '');
  return [
    Number.parseInt(clean.slice(0, 2), 16),
    Number.parseInt(clean.slice(2, 4), 16),
    Number.parseInt(clean.slice(4, 6), 16),
  ];
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60) || 'goal';
}

export async function exportGoalPDF(goal: Goal, category?: Category | null, accent = '#3b82f6'): Promise<void> {
  const { jsPDF } = await import('jspdf');
  const doc = new jsPDF({ unit: 'mm', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  const [ar, ag, ab] = hexToRgb(accent);
  let y = 18;
  let page = 1;

  const setText = (size: number, weight: 'normal' | 'bold' = 'normal', color = 30) => {
    doc.setFont('helvetica', weight);
    doc.setFontSize(size);
    doc.setTextColor(color);
  };
  const label = (text: string, x: number, top: number) => {
    setText(7, 'bold', 120);
    doc.setCharSpace(0.6);
    doc.text(text.toUpperCase(), x, top);
    doc.setCharSpace(0);
  };
  const ensureSpace = (needed: number) => {
    if (y + needed <= pageHeight - 20) return;
    addFooter();
    doc.addPage();
    page += 1;
    y = 20;
    drawPageHeader();
  };
  const drawPageHeader = () => {
    doc.setFillColor(ar, ag, ab);
    doc.rect(0, 0, pageWidth, 2.2, 'F');
    setText(8, 'bold', 110);
    doc.text('MOMENTUM  /  GOAL RECORD', margin, 12);
    doc.setTextColor(160);
    doc.setFont('helvetica', 'normal');
    doc.text(`Page ${page}`, pageWidth - margin, 12, { align: 'right' });
  };
  const addFooter = () => {
    doc.setDrawColor(228, 232, 238);
    doc.setLineWidth(0.3);
    doc.line(margin, pageHeight - 16, pageWidth - margin, pageHeight - 16);
    setText(7.5, 'normal', 140);
    doc.text('Generated by MOMENTUM · Your data stayed on your device', margin, pageHeight - 10);
    doc.text(`Page ${page}`, pageWidth - margin, pageHeight - 10, { align: 'right' });
  };

  // Masthead
  drawPageHeader();
  y = 28;
  doc.setFillColor(8, 12, 19);
  doc.roundedRect(margin, y, 13, 13, 3, 3, 'F');
  doc.setDrawColor(ar, ag, ab);
  doc.setLineWidth(1);
  doc.line(margin + 3, y + 9.4, margin + 5.8, y + 4.5);
  doc.line(margin + 5.8, y + 4.5, margin + 7.4, y + 7.3);
  doc.setDrawColor(255, 255, 255);
  doc.line(margin + 6.4, y + 9.4, margin + 9.2, y + 4.7);
  doc.setDrawColor(ar, ag, ab);
  doc.line(margin + 8.7, y + 9.4, margin + 11.2, y + 4.7);
  doc.setFillColor(ar, ag, ab);
  doc.triangle(margin + 9.4, y + 4.9, margin + 11.6, y + 3.2, margin + 11.8, y + 6.3, 'F');

  label('Goal record', margin + 18, y + 4.5);
  setText(8, 'normal', 125);
  doc.text(
    [category?.name, recurrenceLabel(goal.recurrence), goal.status === 'completed' ? 'Completed' : 'Active']
      .filter(Boolean)
      .join('   ·   '),
    margin + 18,
    y + 9.6,
  );
  y += 22;

  // Title + description
  setText(27, 'bold', 16);
  const titleLines = doc.splitTextToSize(goal.title, contentWidth);
  doc.text(titleLines, margin, y);
  y += titleLines.length * 10 + 2;

  if (goal.description) {
    setText(10, 'normal', 80);
    const lines = doc.splitTextToSize(goal.description, contentWidth);
    const shown = lines.slice(0, 7);
    doc.text(shown, margin, y);
    y += shown.length * 5 + (lines.length > 7 ? 4 : 1);
  }

  // Metadata grid
  const metaY = y + 2;
  const progress = computeGoalProgress(goal);
  const metaItems = [
    ['Deadline', goal.deadline ? formatDate(goal.deadline, 'long') : 'No deadline'],
    ['Progress', `${progress.percent}%  (${progress.completedTasks}/${progress.totalTasks} tasks)`],
    ['Priority', goal.priority.charAt(0).toUpperCase() + goal.priority.slice(1)],
    ['Created', formatDate(goal.createdAt.slice(0, 10), 'medium')],
  ];
  const colWidth = contentWidth / 2;
  metaItems.forEach(([key, value], index) => {
    const col = index % 2;
    const row = Math.floor(index / 2);
    const x = margin + col * colWidth;
    const top = metaY + row * 13;
    label(key, x, top);
    setText(10, 'bold', 40);
    doc.text(value, x, top + 5.5);
  });
  y = metaY + 29;

  // Progress bar
  doc.setFillColor(238, 241, 245);
  doc.roundedRect(margin, y, contentWidth, 4, 2, 2, 'F');
  if (progress.percent > 0) {
    doc.setFillColor(ar, ag, ab);
    doc.roundedRect(margin, y, Math.max(2, (contentWidth * progress.percent) / 100), 4, 2, 2, 'F');
  }
  y += 12;

  // Milestones
  if (goal.milestones.length > 0) {
    ensureSpace(18);
    label('Milestones', margin, y);
    y += 6;
    [...goal.milestones]
      .sort((a, b) => a.order - b.order)
      .forEach((milestone, index) => {
        ensureSpace(18);
        doc.setFillColor(milestone.completed ? ar : 240, milestone.completed ? ag : 242, milestone.completed ? ab : 246);
        doc.circle(margin + 2.2, y - 1.5, 2.4, 'F');
        setText(7, 'bold', milestone.completed ? 255 : 100);
        doc.text(String(index + 1), margin + 2.2, y - 0.6, { align: 'center' });
        setText(11, 'bold', 35);
        doc.text(milestone.title, margin + 8, y);
        setText(8, 'normal', 130);
        const due = milestone.dueDate ? ` · ${formatDate(milestone.dueDate, 'short')}` : '';
        doc.text(milestone.completed ? `Complete${due}` : `Open${due}`, pageWidth - margin, y, { align: 'right' });
        y += 5;
        if (milestone.description) {
          setText(8.5, 'normal', 105);
          const lines = doc.splitTextToSize(milestone.description, contentWidth - 8);
          doc.text(lines.slice(0, 3), margin + 8, y);
          y += Math.min(3, lines.length) * 4;
        }
        y += 4;
      });
    y += 2;
  }

  // Tasks
  ensureSpace(16);
  label('Tasks', margin, y);
  y += 7;
  const rootTasks = goal.tasks.filter((task) => !task.parentTaskId).sort((a, b) => a.order - b.order);
  if (rootTasks.length === 0) {
    setText(9, 'normal', 120);
    doc.text('No tasks recorded yet.', margin, y);
    y += 8;
  }
  for (const task of rootTasks) {
    ensureSpace(14);
    const boxSize = 3.2;
    doc.setDrawColor(160, 170, 182);
    doc.setLineWidth(0.3);
    doc.roundedRect(margin, y - 3.2, boxSize, boxSize, 0.6, 0.6, 'S');
    if (task.completed) {
      doc.setFillColor(ar, ag, ab);
      doc.roundedRect(margin, y - 3.2, boxSize, boxSize, 0.6, 0.6, 'F');
      doc.setDrawColor(255, 255, 255);
      doc.setLineWidth(0.5);
      doc.line(margin + 0.7, y - 1.7, margin + 1.3, y - 1);
      doc.line(margin + 1.3, y - 1, margin + 2.5, y - 2.5);
    }
    setText(9.5, task.completed ? 'normal' : 'bold', task.completed ? 135 : 35);
    const titleWidth = contentWidth - 35;
    const titleLines = doc.splitTextToSize(task.title, titleWidth);
    doc.text(titleLines, margin + 6, y);
    setText(7.5, 'normal', 130);
    const meta = [task.dueDate ? formatDate(task.dueDate, 'short') : null, task.priority !== 'medium' ? task.priority : null]
      .filter(Boolean)
      .join(' · ');
    if (meta) doc.text(meta, pageWidth - margin, y, { align: 'right' });
    y += Math.max(1, titleLines.length) * 4.7 + 2;
    if (task.notes) {
      setText(7.8, 'normal', 125);
      const noteLines = doc.splitTextToSize(task.notes, contentWidth - 10).slice(0, 2);
      doc.text(noteLines, margin + 6, y);
      y += noteLines.length * 3.8;
    }
    const subtasks = goal.tasks.filter((subtask) => subtask.parentTaskId === task.id);
    for (const subtask of subtasks) {
      ensureSpace(8);
      doc.setDrawColor(190, 198, 208);
      doc.circle(margin + 8, y - 1.1, 1.2, 'S');
      setText(8.5, 'normal', subtask.completed ? 145 : 70);
      const subLines = doc.splitTextToSize(subtask.title, contentWidth - 22);
      doc.text(subLines, margin + 12, y);
      y += Math.max(1, subLines.length) * 4.2 + 1;
    }
    y += 1.5;
  }

  // Notes
  if (goal.notes) {
    ensureSpace(24);
    label('Notes', margin, y);
    y += 6;
    setText(9, 'normal', 75);
    const lines = doc.splitTextToSize(goal.notes, contentWidth);
    for (const line of lines) {
      ensureSpace(7);
      doc.text(line, margin, y);
      y += 4.7;
    }
    y += 4;
  }

  // Finance
  if (goal.finance?.enabled) {
    ensureSpace(28);
    label('Financial tracking', margin, y);
    y += 8;
    const currency = goal.finance.currency || 'USD';
    setText(10, 'normal', 65);
    doc.text(
      `${currency} ${goal.finance.currentAmount.toLocaleString()} of ${goal.finance.targetAmount.toLocaleString()}`,
      margin,
      y,
    );
    y += 6;
    doc.setFillColor(238, 241, 245);
    doc.roundedRect(margin, y, contentWidth, 3.5, 1.75, 1.75, 'F');
    const financePercent = goal.finance.targetAmount > 0
      ? Math.min(100, (goal.finance.currentAmount / goal.finance.targetAmount) * 100)
      : 0;
    if (financePercent > 0) {
      doc.setFillColor(ar, ag, ab);
      doc.roundedRect(margin, y, Math.max(2, (contentWidth * financePercent) / 100), 3.5, 1.75, 1.75, 'F');
    }
    y += 10;
  }

  addFooter();
  const deadlinePart = parseDateOnly(goal.deadline) ? `-${goal.deadline}` : '';
  doc.save(`momentum-${slugify(goal.title)}${deadlinePart}.pdf`);
}
